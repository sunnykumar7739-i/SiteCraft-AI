import { STYLE_PRESETS, type Project, type ScrapedContent } from "@/lib/types";

/**
 * Offline fallback used when no AI provider key is configured, so the whole
 * product flow (create → variants → edit → export) can be demoed locally.
 */
export async function* mockGenerate(project: Project, styleKey: string, scraped: ScrapedContent | null) {
  const preset = STYLE_PRESETS.find((s) => s.key === styleKey) ?? STYLE_PRESETS[0];
  const dark = preset.theme === "dark";
  const brand = scraped?.brand || project.name;
  const tagline =
    scraped?.description ||
    project.description?.split(/[.\n]/)[0] ||
    "A modern website generated by SiteCraft AI. Connect an API key to get real AI designs.";
  const headings = scraped?.headings.slice(0, 3) ?? ["Built for people who ship", "Everything in one place", "Loved by teams"];
  const paras =
    scraped?.paragraphs.slice(0, 3) ??
    [
      "Describe what you need and get a complete, responsive page in seconds.",
      "Edit with plain-language prompts or click any element to change it visually.",
      "Export clean HTML + Tailwind and host it anywhere.",
    ];
  const palette = {
    "minimal-light": ["#ffffff", "#0f172a", "#2563eb"],
    "bold-light": ["#fffaf0", "#111111", "#ff3d00"],
    "luxe-dark": ["#0f0b07", "#f5efe4", "#e3b341"],
    "playful-light": ["#fff7fb", "#2b2d42", "#ff6b9d"],
    "editorial-light": ["#f7f3ea", "#141414", "#9a2b2b"],
    "glass-dark": ["#070b1a", "#e8ecff", "#7c9cff"],
    "brutalist-light": ["#ffffff", "#000000", "#c6ff00"],
    "corporate-light": ["#f8fafc", "#0b1f3a", "#0b63ce"],
  }[styleKey] ?? ["#ffffff", "#0f172a", "#2563eb"];
  const [bg, fg, accent] = palette;

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<title>${esc(brand)}</title>
<script src="https://cdn.tailwindcss.com"></script>
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;800&display=swap" rel="stylesheet" />
<style>body{font-family:Inter,ui-sans-serif,system-ui;background:${bg};color:${fg}} .accent{color:${accent}} .bg-accent{background:${accent}} .border-accent{border-color:${accent}}</style>
</head>
<body>
<!-- Generated by SiteCraft AI (offline mock – add ANTHROPIC_API_KEY for real AI output) -->
<header class="sticky top-0 z-10 backdrop-blur border-b ${dark ? "border-white/10 bg-black/30" : "border-black/10 bg-white/60"}">
  <div class="max-w-6xl mx-auto px-6 h-16 flex items-center justify-between">
    <a href="#" class="font-extrabold text-xl tracking-tight" data-sc-editable="true">${esc(brand)}</a>
    <nav class="hidden md:flex gap-8 text-sm font-medium">
      ${(scraped?.links.slice(0, 4) ?? [{ text: "Features", href: "#features" }, { text: "About", href: "#about" }, { text: "Contact", href: "#contact" }])
        .map((l) => `<a href="${esc(l.href)}" class="hover:opacity-70" data-sc-editable="true">${esc(l.text)}</a>`)
        .join("\n      ")}
    </nav>
    <a href="#contact" class="bg-accent text-white px-4 py-2 rounded-full text-sm font-semibold" data-sc-editable="true">Get started</a>
  </div>
</header>

<section class="max-w-6xl mx-auto px-6 pt-24 pb-20 grid md:grid-cols-12 gap-10 items-center">
  <div class="md:col-span-7">
    <p class="accent font-semibold tracking-widest uppercase text-xs mb-4" data-sc-editable="true">${esc(preset.label)} · ${dark ? "Dark" : "Light"}</p>
    <h1 class="text-5xl md:text-7xl font-extrabold leading-[0.95] tracking-tight" data-sc-editable="true">${esc(headings[0] ?? brand)}</h1>
    <p class="mt-6 text-lg md:text-xl opacity-80 max-w-xl" data-sc-editable="true">${esc(tagline)}</p>
    <div class="mt-10 flex flex-wrap gap-3">
      <a href="#contact" class="bg-accent text-white px-6 py-3 rounded-full font-semibold" data-sc-editable="true">Start now</a>
      <a href="#features" class="border ${dark ? "border-white/30" : "border-black/20"} px-6 py-3 rounded-full font-semibold" data-sc-editable="true">See how it works</a>
    </div>
  </div>
  <div class="md:col-span-5">
    <div class="aspect-[4/5] rounded-3xl overflow-hidden shadow-2xl">
      <img alt="${esc(brand)} hero" class="w-full h-full object-cover" src="https://picsum.photos/seed/${encodeURIComponent(styleKey)}/800/1000" />
    </div>
  </div>
</section>

<section id="features" class="${dark ? "bg-white/5" : "bg-black/5"} py-20">
  <div class="max-w-6xl mx-auto px-6">
    <h2 class="text-3xl md:text-5xl font-extrabold tracking-tight max-w-2xl" data-sc-editable="true">${esc(headings[1] ?? "What you get")}</h2>
    <div class="mt-12 grid md:grid-cols-3 gap-8">
      ${paras
        .map(
          (p, i) => `<div class="p-8 rounded-2xl ${dark ? "bg-black/40 border border-white/10" : "bg-white border border-black/10"}">
        <div class="w-10 h-10 rounded-xl bg-accent/20 flex items-center justify-center mb-6"><span class="accent font-bold">${i + 1}</span></div>
        <p class="leading-relaxed opacity-90" data-sc-editable="true">${esc(p)}</p>
      </div>`,
        )
        .join("\n      ")}
    </div>
  </div>
</section>

<section id="about" class="max-w-6xl mx-auto px-6 py-24 grid md:grid-cols-2 gap-12 items-center">
  <img alt="About ${esc(brand)}" class="rounded-3xl w-full aspect-square object-cover" src="https://picsum.photos/seed/${encodeURIComponent(brand)}/900/900" />
  <div>
    <h2 class="text-3xl md:text-5xl font-extrabold tracking-tight" data-sc-editable="true">${esc(headings[2] ?? "Why " + brand)}</h2>
    <p class="mt-6 text-lg opacity-80 leading-relaxed" data-sc-editable="true">${esc(paras[0] ?? tagline)}</p>
    <ul class="mt-8 space-y-3 text-base">
      <li class="flex gap-3"><span class="accent">✓</span><span data-sc-editable="true">Responsive on every device</span></li>
      <li class="flex gap-3"><span class="accent">✓</span><span data-sc-editable="true">Clean, exportable code</span></li>
      <li class="flex gap-3"><span class="accent">✓</span><span data-sc-editable="true">Editable with AI prompts</span></li>
    </ul>
  </div>
</section>

<section id="contact" class="bg-accent text-white">
  <div class="max-w-6xl mx-auto px-6 py-20 flex flex-col md:flex-row items-center justify-between gap-8">
    <h2 class="text-3xl md:text-4xl font-extrabold tracking-tight" data-sc-editable="true">Ready to work with ${esc(brand)}?</h2>
    <a href="mailto:hello@example.com" class="bg-white text-black px-8 py-4 rounded-full font-semibold" data-sc-editable="true">Contact us</a>
  </div>
</section>

<footer class="max-w-6xl mx-auto px-6 py-10 text-sm opacity-60 flex flex-col md:flex-row justify-between gap-4">
  <p data-sc-editable="true">© ${new Date().getFullYear()} ${esc(brand)}. All rights reserved.</p>
  <p data-sc-editable="true">Made with SiteCraft AI</p>
</footer>
</body>
</html>`;

  // stream it in chunks to exercise the same code path as real models
  for (let i = 0; i < html.length; i += 400) {
    yield html.slice(i, i + 400);
    await new Promise((r) => setTimeout(r, 12));
  }
}

export async function* mockEdit(html: string, instruction: string) {
  const note = `<!-- Mock edit applied: ${esc(instruction)} (configure an AI key for real edits) -->`;
  const out = html.includes("</body>") ? html.replace("</body>", `${note}\n</body>`) : html + note;
  for (let i = 0; i < out.length; i += 800) {
    yield out.slice(i, i + 800);
    await new Promise((r) => setTimeout(r, 5));
  }
}

function esc(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}
